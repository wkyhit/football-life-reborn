      readonly category: "special";
      readonly choices: readonly ClassicChoiceLogEntry[];
      readonly contentVersion: ClassicGoldenState["contentVersion"];
      readonly expected: ClassicGoldenState;
      readonly id: string;
      readonly identity: ClassicIdentity;
      readonly mode: PacingMode;
